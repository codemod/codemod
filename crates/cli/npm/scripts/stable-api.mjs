// Review compatibility before regenerating:
// pnpm --filter codemod snapshot:stable-api --update
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

const root = new URL("../", import.meta.url);
const snapshot = new URL("tests/snapshots/stable-api.d.ts", root);
const { exports } = JSON.parse(readFileSync(new URL("package.json", root), "utf8"));
const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });

const types = [
  "index.d.ts",
  "workflow.d.ts",
  "main.d.ts",
  "files.d.ts",
  "runtime.d.ts",
  "protocol.d.ts",
  "modules/workflow.d.ts",
  "modules/files.d.ts",
  "modules/ast-grep.d.ts",
  "modules/runtime.d.ts",
  "modules/protocol.d.ts",
  "modules/langs.d.ts",
];

function stableDeclarations(path) {
  const content = readFileSync(new URL(`types/${path}`, root), "utf8");
  const source = ts.createSourceFile(path, content, ts.ScriptTarget.Latest, true);
  const { transformed, dispose } = ts.transform(source, [
    (context) => {
      // Visit members too: SgNode is stable, but its semantic methods are not.
      function visit(node) {
        if (ts.getJSDocTags(node).some(({ tagName }) => tagName.text === "experimental")) {
          return undefined;
        }
        return ts.visitEachChild(node, visit, context);
      }
      return (file) => ts.visitNode(file, visit);
    },
  ]);
  const printed = printer.printFile(transformed[0]);
  dispose();
  return `// ${path}\n${printed}`;
}

const routes = [
  ".",
  "./workflow",
  "./ast-grep",
  "./ast-grep/langs/*",
  "./langs/*",
  "./main",
  "./files",
  "./runtime",
  "./protocol",
];
const output = [
  "// Stable TypeScript API snapshot; generated by scripts/stable-api.mjs.",
  "// oxlint-disable triple-slash-reference",
  ...routes.map((route) => `// ${route}: ${JSON.stringify(exports[route])}`),
  "",
  types.map(stableDeclarations).join("\n"),
].join("\n");

if (process.argv.includes("--update")) {
  writeFileSync(snapshot, output);
} else {
  assert.ok(
    output === readFileSync(snapshot, "utf8").replaceAll("\r\n", "\n"),
    "Stable declaration snapshot changed. Review compatibility before updating it.",
  );
}
