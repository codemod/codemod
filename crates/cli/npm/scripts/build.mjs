// Builds this package's JavaScript and type declarations from the TypeScript
// in `src/`: `runtime/`, `testing/`, `register.*` and `vite.*`. Nothing it
// writes is committed.
//
// The orchestrator is shared with the engine and lives there
// (crates/workflow/src/js/orchestrator.ts). It is copied in before tsc runs,
// with a module that identifies that source, so the host can tell when the
// native addon was built from another version of it.

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = (path) => fileURLToPath(new URL(path, import.meta.url));

const source = readFileSync(here("../../../workflow/src/js/orchestrator.ts"), "utf8");
const GENERATED =
  "// Generated by scripts/build.mjs from crates/workflow/src/js/orchestrator.ts; do not edit.\n\n";
// As `orchestrator_version` in crates/workflow/src/js.rs: line endings do not count.
const version = createHash("sha256").update(source.replaceAll("\r", "")).digest("hex");

writeIfChanged(here("../src/runtime/orchestrator.mts"), GENERATED + source);
writeIfChanged(
  here("../src/runtime/jssg-compat.mts"),
  GENERATED.replace("orchestrator.ts", "jssg_compat.ts") +
    readFileSync(here("../../../workflow/src/js/jssg_compat.ts"), "utf8")
      .replace('from "codemod/ast-grep"', 'from "./ast-grep.mts"')
      .replace('from "codemod-internal:orchestrator"', 'from "./orchestrator.mts"'),
);
writeIfChanged(
  here("../src/runtime/assess-core.mts"),
  GENERATED.replace("orchestrator.ts", "assess.ts") +
    readFileSync(here("../../../workflow/src/js/assess.ts"), "utf8"),
);
writeIfChanged(
  here("../src/runtime/orchestrator-version.mts"),
  `${GENERATED}/** Identifies the orchestrator source this package was built from. */\nexport const ORCHESTRATOR_VERSION = "${version}";\n`,
);

for (const output of [
  "runtime",
  "testing",
  "register.mjs",
  "register.d.mts",
  "vite.mjs",
  "vite.d.mts",
]) {
  rmSync(here(`../${output}`), { recursive: true, force: true });
}

const tsc = createRequire(import.meta.url).resolve("typescript/bin/tsc");
const built = spawnSync(process.execPath, [tsc, "-p", here("../tsconfig.build.json")], {
  stdio: "inherit",
});
process.exitCode = built.status ?? 1;

/** Leave an unchanged file alone, so editors and watchers do not see it change. */
function writeIfChanged(path, text) {
  let current;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    // not there yet
  }
  if (current !== text) writeFileSync(path, text);
}
