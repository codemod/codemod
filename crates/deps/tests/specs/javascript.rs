use super::*;

const APP_PACKAGE_JSON_V1: &str = r#"{ "name": "app", "version": "1.0.0", "workspaces": ["packages/*"],
  "dependencies": { "loose-envify": "^1.1.0", "lib": "^2.0.0", "foo": "npm:is-number@^7.0.0" },
  "devDependencies": { "js-tokens": "^3.0.0" },
  "optionalDependencies": { "is-odd": "^3.0.1" } }"#;

const LIB_PACKAGE_JSON: &str =
    r#"{ "name": "lib", "version": "2.0.0", "dependencies": { "js-tokens": "^4.0.0" } }"#;

const YARN_1_LOCK: &str = r#"# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"foo@npm:is-number@^7.0.0":
  version "7.0.0"
  resolved "https://registry.yarnpkg.com/is-number/-/is-number-7.0.0.tgz"

is-number@^6.0.0:
  version "6.0.0"

is-odd@^3.0.1:
  version "3.0.1"
  dependencies:
    is-number "^6.0.0"

js-tokens@^3.0.0:
  version "3.0.2"

"js-tokens@^3.0.0 || ^4.0.0", js-tokens@^4.0.0:
  version "4.0.0"
  integrity sha512-x

loose-envify@^1.1.0:
  version "1.4.0"
  dependencies:
    js-tokens "^3.0.0 || ^4.0.0"
  optionalDependencies:
    is-odd "^3.0.1"
"#;

fn manifests(path: &str) -> Option<String> {
    match path {
        "package.json" => Some(APP_PACKAGE_JSON_V1.into()),
        "packages/lib/package.json" => Some(LIB_PACKAGE_JSON.into()),
        _ => None,
    }
}

fn yarn_1() -> Graph {
    lockfiles::yarn(YARN_1_LOCK, &manifests, &["packages/lib".into()]).unwrap()
}

fn dependencies_of(graph: Graph, name: &str) -> Vec<String> {
    let walk = Walk::new(graph);
    let node = walk.nodes_named(name)[0];
    described(&walk, walk.dependencies(node, &[]))
}

#[test]
fn a_yarn_1_entry_satisfies_every_descriptor_in_its_key() {
    assert_eq!(
        chains_to(yarn_1(), "js-tokens", &[Kind::Prod]),
        [
            "app@1.0.0 > loose-envify@1.4.0 > js-tokens@4.0.0",
            "lib@2.0.0 > js-tokens@4.0.0"
        ]
    );
}

#[test]
fn a_yarn_1_workspace_takes_ranges_and_kinds_from_its_package_json() {
    assert_eq!(
        workspace_dependencies(yarn_1(), &[Kind::Dev, Kind::Optional]),
        [
            "app@1.0.0 dev js-tokens@3.0.2 ^3.0.0",
            "app@1.0.0 optional is-odd@3.0.1 ^3.0.1"
        ]
    );
}

#[test]
fn a_yarn_1_dependency_on_another_workspace_resolves_to_it() {
    assert_eq!(
        chains_to(yarn_1(), "lib", &[Kind::Prod]),
        ["app@1.0.0 > lib@2.0.0"]
    );
}

#[test]
fn a_yarn_1_alias_is_the_package_it_aliases() {
    assert_eq!(
        chains_to(yarn_1(), "is-number", &[Kind::Prod]),
        ["app@1.0.0 > is-number@7.0.0"]
    );
}

#[test]
fn a_yarn_1_optional_dependency_of_a_package_is_an_optional_edge() {
    assert_eq!(
        dependencies_of(yarn_1(), "loose-envify"),
        [
            "loose-envify@1.4.0 prod js-tokens@4.0.0 ^3.0.0 || ^4.0.0",
            "loose-envify@1.4.0 optional is-odd@3.0.1 ^3.0.1"
        ]
    );
}

#[test]
fn yarn_1_workspaces_are_the_directories_the_root_globs_name() {
    let dir = repository(&[
        ("package.json", APP_PACKAGE_JSON_V1),
        ("packages/lib/package.json", LIB_PACKAGE_JSON),
        ("packages/lib/fixtures/old/package.json", "{}"),
        ("yarn.lock", YARN_1_LOCK),
    ]);
    assert_eq!(lockfiles::yarn_workspaces(dir.path()), ["packages/lib"]);
    let graph = lockfiles::load(dir.path(), &[]).unwrap();
    assert!(graph.skipped.is_empty());
    assert_eq!(Walk::new(graph).workspaces().len(), 2);
}

const PACKAGE_LOCK_V1: &str = r#"{
  "name": "app", "version": "1.0.0", "lockfileVersion": 1, "requires": true,
  "dependencies": {
    "foo": { "version": "npm:is-number@7.0.0" },
    "js-tokens": { "version": "3.0.2", "dev": true },
    "loose-envify": {
      "version": "1.4.0",
      "requires": { "js-tokens": "^3.0.0 || ^4.0.0" },
      "dependencies": { "js-tokens": { "version": "4.0.0" } }
    }
  }
}"#;

fn package_lock_v1() -> Graph {
    lockfiles::package_lock(PACKAGE_LOCK_V1, &manifests).unwrap()
}

#[test]
fn package_lock_v1_resolves_a_nested_copy_before_the_hoisted_one() {
    assert_eq!(
        dependencies_of(package_lock_v1(), "loose-envify"),
        ["loose-envify@1.4.0 prod js-tokens@4.0.0 ^3.0.0 || ^4.0.0"]
    );
}

#[test]
fn package_lock_v1_root_takes_ranges_and_kinds_from_package_json() {
    assert_eq!(
        workspace_dependencies(package_lock_v1(), &[Kind::Dev]),
        ["app@1.0.0 dev js-tokens@3.0.2 ^3.0.0"]
    );
}

#[test]
fn a_package_lock_v1_alias_is_the_package_it_aliases() {
    assert_eq!(
        chains_to(package_lock_v1(), "is-number", &[]),
        ["app@1.0.0 > is-number@7.0.0"]
    );
}

#[test]
fn a_package_lock_beside_npm_shrinkwrap_json_is_not_read() {
    let dir = repository(&[
        ("package.json", APP_PACKAGE_JSON_V1),
        ("npm-shrinkwrap.json", PACKAGE_LOCK_V1),
        ("package-lock.json", PACKAGE_LOCK_V1),
    ]);
    let graph = lockfiles::load(dir.path(), &[]).unwrap();
    assert_eq!(graph.lockfiles, ["npm-shrinkwrap.json"]);
}

#[test]
fn npm_shrinkwrap_json_is_read_as_a_package_lock() {
    let dir = repository(&[
        ("package.json", APP_PACKAGE_JSON_V1),
        ("npm-shrinkwrap.json", PACKAGE_LOCK_V1),
    ]);
    let graph = lockfiles::load(dir.path(), &[]).unwrap();
    assert_eq!(graph.lockfiles, ["npm-shrinkwrap.json"]);
    assert_eq!(
        chains_to(graph, "js-tokens", &[Kind::Prod]),
        ["app@1.0.0 > loose-envify@1.4.0 > js-tokens@4.0.0"]
    );
}

