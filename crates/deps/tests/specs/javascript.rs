fn yarn_v1_monorepo() -> tempfile::TempDir {
    repository(&[
        ("yarn.lock", YARN_V1_LOCK),
        (
            "package.json",
            r#"{ "private": true, "workspaces": ["packages/*"], "devDependencies": { "typescript": "^5.0.0" } }"#,
        ),
        (
            "packages/web/package.json",
            r#"{ "name": "@demo/web", "version": "1.0.0", "dependencies": { "@demo/shared": "^1.0.0", "react": "^18.2.0", "string-width-cjs": "npm:string-width@^4.2.0" } }"#,
        ),
        (
            "packages/shared/package.json",
            r#"{ "name": "@demo/shared", "version": "1.0.0", "dependencies": { "moment": "^2.29.0" }, "peerDependencies": { "react": ">=17" } }"#,
        ),
        // Not a workspace: no pattern names it.
        (
            "examples/demo/package.json",
            r#"{ "name": "demo", "dependencies": { "moment": "^2.29.0" } }"#,
        ),
    ])
}

#[test]
fn a_yarn_1_lockfile_is_read_with_its_workspaces_from_package_json() {
    let dir = yarn_v1_monorepo();
    let graph = lockfiles::load(dir.path(), &[]).unwrap();
    assert_eq!(graph.lockfiles, vec!["yarn.lock".to_string()]);
    assert!(graph.skipped.is_empty());
    let walk = Walk::new(graph);
    let mut dirs: Vec<String> = walk
        .workspaces()
        .into_iter()
        .map(|id| {
            format!(
                "{} {}",
                walk.graph.nodes[id].workspace.clone().unwrap(),
                walk.graph.label(id)
            )
        })
        .collect();
    dirs.sort();
    assert_eq!(
        dirs,
        [
            ". <.>@0.0.0-use.local",
            "packages/shared @demo/shared@1.0.0",
            "packages/web @demo/web@1.0.0"
        ]
    );
}

#[test]
fn a_yarn_1_chain_crosses_workspaces_and_shared_descriptors() {
    let dir = yarn_v1_monorepo();
    let graph = || lockfiles::load(dir.path(), &[]).unwrap();
    assert_eq!(
        chains_to(graph(), "js-tokens", &[]),
        ["@demo/web@1.0.0 > react@18.2.0 > loose-envify@1.4.0 > js-tokens@4.0.0"]
    );
    assert_eq!(
        chains_to(graph(), "moment", &[]),
        [
            "@demo/shared@1.0.0 > moment@2.29.4",
            "@demo/web@1.0.0 > @demo/shared@1.0.0 > moment@2.29.4"
        ]
    );
}

#[test]
fn a_yarn_1_workspace_takes_kinds_and_ranges_from_its_package_json() {
    let dir = yarn_v1_monorepo();
    let walk = Walk::new(lockfiles::load(dir.path(), &[]).unwrap());
    let edges = |name: &str| {
        let id = walk.nodes_named(name)[0];
        described(&walk, walk.dependencies(id, &[]))
    };
    assert_eq!(
        edges("<.>"),
        ["<.>@0.0.0-use.local dev typescript@5.4.5 ^5.0.0"]
    );
    assert_eq!(
        edges("@demo/shared"),
        [
            "@demo/shared@1.0.0 prod moment@2.29.4 ^2.29.0",
            "@demo/shared@1.0.0 peer react >=17"
        ]
    );
    // An alias is the package it aliases.
    assert_eq!(
        edges("@demo/web"),
        [
            "@demo/web@1.0.0 prod @demo/shared@1.0.0 ^1.0.0",
            "@demo/web@1.0.0 prod react@18.2.0 ^18.2.0",
            "@demo/web@1.0.0 prod string-width@4.2.3 npm:string-width@^4.2.0"
        ]
    );
    // Lock entries keep ranges, and optional dependencies stay optional.
    assert_eq!(
        edges("react"),
        [
            "react@18.2.0 prod loose-envify@1.4.0 ^1.1.0",
            "react@18.2.0 optional fsevents ~2.3.2"
        ]
    );
}

#[test]
fn a_yarn_1_project_without_workspaces_is_its_own_root() {
    let graph = lockfiles::yarn(YARN_V1_LOCK, &|path| {
        (path == "package.json").then(|| {
            r#"{ "name": "app", "version": "2.0.0", "dependencies": { "react": "^18.2.0" } }"#
                .into()
        })
    })
    .unwrap();
    assert_eq!(
        workspace_dependencies(graph, &[]),
        ["app@2.0.0 prod react@18.2.0 ^18.2.0"]
    );
}

const PACKAGE_LOCK_V1: &str = r#"{
  "name": "app",
  "version": "1.0.0",
  "lockfileVersion": 1,
  "requires": true,
  "dependencies": {
    "a": {
      "version": "1.0.0",
      "requires": { "b": "^1.0.0" },
      "dependencies": { "b": { "version": "1.5.0" } }
    },
    "b": { "version": "2.1.0" },
    "foo": { "version": "npm:bar@1.2.0" },
    "typescript": { "version": "5.4.5", "dev": true }
  }
}"#;

#[test]
fn a_package_lock_v1_takes_the_root_ranges_from_package_json() {
    let graph = lockfiles::package_lock(PACKAGE_LOCK_V1, &|path| {
        (path == "package.json").then(|| {
            r#"{ "name": "app", "version": "1.0.0", "dependencies": { "a": "^1.0.0", "b": "^2.0.0", "foo": "npm:bar@^1.0.0" }, "devDependencies": { "typescript": "^5.0.0" } }"#.into()
        })
    })
    .unwrap();
    let walk = Walk::new(graph);
    let root = walk.workspaces()[0];
    assert_eq!(
        described(&walk, walk.dependencies(root, &[])),
        [
            "app@1.0.0 prod a@1.0.0 ^1.0.0",
            "app@1.0.0 prod b@2.1.0 ^2.0.0",
            "app@1.0.0 prod bar@1.2.0 npm:bar@^1.0.0",
            "app@1.0.0 dev typescript@5.4.5 ^5.0.0"
        ]
    );
    let a = walk.nodes_named("a")[0];
    assert_eq!(
        described(&walk, walk.dependencies(a, &[])),
        ["a@1.0.0 prod b@1.5.0 ^1.0.0"]
    );
}

#[test]
