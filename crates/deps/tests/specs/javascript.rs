const BUN_LOCK: &str = r#"{
  "lockfileVersion": 1,
  "workspaces": {
    "": {
      "name": "app",
      "dependencies": {
        "@demo/shared": "workspace:*",
        "react": "^18.2.0",
      },
      "devDependencies": {
        "typescript": "^5.0.0",
      },
    },
    "packages/shared": {
      "name": "@demo/shared",
      "version": "1.0.0",
      "dependencies": {
        "loose-envify": "^1.0.0",
      },
      "peerDependencies": {
        "react": ">=17",
      },
    },
  },
  "packages": {
    "@demo/shared": ["@demo/shared@workspace:packages/shared"],

    "@demo/shared/loose-envify": ["loose-envify@1.0.0", "", {}, "sha512-c"],

    "js-tokens": ["js-tokens@4.0.0", "", {}, "sha512-a"],

    "loose-envify": ["loose-envify@1.4.0", "", { "dependencies": { "js-tokens": "^3.0.0 || ^4.0.0" }, "bin": { "loose-envify": "cli.js" } }, "sha512-b"],

    "react": ["react@18.2.0", "", { "dependencies": { "loose-envify": "^1.1.0" } }, "sha512-d"],

    "typescript": ["typescript@5.4.5", "", { "bin": { "tsc": "bin/tsc" } }, "sha512-e"],
  }
}
"#;

#[test]
fn a_bun_lock_resolves_nested_copies_before_hoisted_ones() {
    let dir = repository(&[("bun.lock", BUN_LOCK)]);
    let graph = lockfiles::load(dir.path(), &[]).unwrap();
    assert_eq!(graph.lockfiles, vec!["bun.lock".to_string()]);
    let walk = Walk::new(graph);
    let edges = |name: &str| {
        let id = walk.nodes_named(name)[0];
        described(&walk, walk.dependencies(id, &[]))
    };
    assert_eq!(
        edges("app"),
        [
            "app@0.0.0-use.local prod @demo/shared@1.0.0 workspace:*",
            "app@0.0.0-use.local prod react@18.2.0 ^18.2.0",
            "app@0.0.0-use.local dev typescript@5.4.5 ^5.0.0"
        ]
    );
    assert_eq!(
        edges("@demo/shared"),
        [
            "@demo/shared@1.0.0 prod loose-envify@1.0.0 ^1.0.0",
            "@demo/shared@1.0.0 peer react >=17"
        ]
    );
    assert_eq!(
        edges("react"),
        ["react@18.2.0 prod loose-envify@1.4.0 ^1.1.0"]
    );
}

#[test]
fn a_bun_lock_chain_goes_through_the_hoisted_copy() {
    let graph = lockfiles::bun(BUN_LOCK).unwrap();
    assert_eq!(
        chains_to(graph, "js-tokens", &[]),
        ["app@0.0.0-use.local > react@18.2.0 > loose-envify@1.4.0 > js-tokens@4.0.0"]
    );
}

