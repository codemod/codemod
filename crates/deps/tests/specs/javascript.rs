const BUN_LOCK: &str = r#"{
  "lockfileVersion": 1,
  "workspaces": {
    "": {
      "name": "app",
      "dependencies": {
        "foo": "npm:is-number@^7.0.0",
        "lib": "^2.0.0",
        "loose-envify": "^1.1.0",
      },
      "devDependencies": {
        "js-tokens": "^3.0.0",
      },
    },
    "packages/lib": {
      "name": "lib",
      "version": "2.0.0",
      "dependencies": {
        "js-tokens": "^4.0.0",
      },
    },
  },
  "packages": {
    "foo": ["is-number@7.0.0", "", {}, "sha512-a"],

    "js-tokens": ["js-tokens@3.0.2", "", {}, "sha512-b"],

    "lib": ["lib@workspace:packages/lib"],

    "loose-envify": ["loose-envify@1.4.0", "", { "dependencies": { "js-tokens": "^3.0.0 || ^4.0.0" }, "bin": { "loose-envify": "cli.js" } }, "sha512-c"],

    "lib/js-tokens": ["js-tokens@4.0.0", "", {}, "sha512-d"],

    "loose-envify/js-tokens": ["js-tokens@4.0.0", "", {}, "sha512-d"],
  }
}"#;

fn bun() -> Graph {
    lockfiles::bun(BUN_LOCK, &manifests).unwrap()
}

#[test]
fn a_bun_workspace_takes_ranges_and_kinds_from_the_lockfile() {
    assert_eq!(
        workspace_dependencies(bun(), &[Kind::Dev]),
        ["app@1.0.0 dev js-tokens@3.0.2 ^3.0.0"]
    );
}

#[test]
fn a_bun_package_resolves_its_nested_copy_before_the_hoisted_one() {
    assert_eq!(
        chains_to(bun(), "js-tokens", &[Kind::Prod]),
        [
            "app@1.0.0 > loose-envify@1.4.0 > js-tokens@4.0.0",
            "lib@2.0.0 > js-tokens@4.0.0"
        ]
    );
}

#[test]
fn bun_aliases_and_workspace_dependencies_resolve_to_their_packages() {
    let walk = Walk::new(bun());
    let root = walk.workspaces()[0];
    let mut targets: Vec<String> = described(&walk, walk.dependencies(root, &[Kind::Prod]));
    targets.sort();
    assert_eq!(
        targets,
        [
            "app@1.0.0 prod is-number@7.0.0 npm:is-number@^7.0.0",
            "app@1.0.0 prod lib@2.0.0 ^2.0.0",
            "app@1.0.0 prod loose-envify@1.4.0 ^1.1.0"
        ]
    );
}

#[test]
fn bun_lockb_beside_a_bun_lock_is_not_reported() {
    let dir = repository(&[
        ("package.json", APP_PACKAGE_JSON_V1),
        ("bun.lock", BUN_LOCK),
        ("bun.lockb", BUN_LOCKB),
    ]);
    let graph = lockfiles::load(dir.path(), &[]).unwrap();
    assert_eq!(graph.lockfiles, ["bun.lock"]);
    assert!(graph.skipped.is_empty());
}
